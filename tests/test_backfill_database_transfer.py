def test_scoped_copy_preserves_bytes_times_enrichment_and_composite_keys(
    databases, tmp_path
):
    source, target = databases
    snapshot = transfer.export_snapshot(source, target, tmp_path, ["july-"])
    source.rollback()
    target.rollback()
    result = transfer.import_snapshot(target, tmp_path)
    target.commit()
    assert result["status"] == "verified"
    assert target.execute("SELECT tweet_id,body FROM posts").fetchall() == [
        ("kept", b"\x00\xff\n")
    ]
    assert target.execute("SELECT byte_count FROM posts").fetchone()[0] == 3
    assert target.execute("SELECT id FROM collection_evidence_archives").fetchall() == [
        (2,)
    ]
    assert target.execute(
        "SELECT locale,text FROM post_translation_texts"
    ).fetchall() == [("ja", "日本語")]
    assert (
        target.execute(
            "INSERT INTO post_translation_artifacts(post_id,content) VALUES ('kept','{}') RETURNING id"
        ).fetchone()[0]
        == 31
    )
    target.commit()
    assert transfer.import_snapshot(target, tmp_path)["status"] == "already_imported"
    assert snapshot["tables"]["posts"]["rows"] == 1
    assert snapshot["tables"]["collection_scope_runs"]["rows"] == 1200
    assert target.execute("SELECT count(*) FROM collection_scope_runs").fetchone()[0] == 1200
    assert source.execute("SELECT count(*) FROM posts").fetchone()[0] == 2


def test_changed_export_never_reaches_destination(databases, tmp_path):
    source, target = databases
    transfer.export_snapshot(source, target, tmp_path, ["july-"])
    source.rollback()
    target.rollback()
    value = json.loads((tmp_path / "snapshot.json").read_text())
    value["tables"]["posts"]["rows"] = 50
    (tmp_path / "snapshot.json").write_text(json.dumps(value))
    with pytest.raises(ValueError, match="manifest_changed"):
        transfer.import_snapshot(target, tmp_path)
    target.rollback()
    assert target.execute("SELECT count(*) FROM posts").fetchone()[0] == 0
